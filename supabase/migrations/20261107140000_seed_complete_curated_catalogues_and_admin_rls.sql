-- 5. User-Scoped Notifications Inbox Table
create table if not exists public.user_notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null check (category in ('system', 'opportunity', 'pickup_game', 'booking', 'verification', 'message')),
  title text not null check (char_length(trim(title)) between 2 and 200),
  message text not null check (char_length(trim(message)) >= 2),
  action_url text check (action_url is null or action_url ~ '^(/|https?://)'),
  is_read boolean not null default false,
  metadata jsonb default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_user_notifications_user_created
  on public.user_notifications(user_id, created_at desc);

alter table public.user_notifications enable row level security;

drop policy if exists "user_notifications_read_own" on public.user_notifications;
